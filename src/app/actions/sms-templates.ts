const listTemplatesSchema = z.object({ categoryId: z.string().min(1).optional() });

export async function listSmsTemplatesAction(rawInput?: unknown): Promise<ActionResult<SmsTemplate[]>> {
    const input = listTemplatesSchema.parse(rawInput ?? {});
    const ctx = await requireEffectivePermission('canViewSMS');

    let query = ctx.client.from('sms_templates').select('*').eq('org_id', ctx.orgId);
    if (input.categoryId) query = query.eq('category_id', input.categoryId);
    const { data, error } = await query.order('created_at', { ascending: true });
    if (error) return fail('query_failed', error.message);
    return ok((data as TemplateRow[]).map(mapTemplate));
}

