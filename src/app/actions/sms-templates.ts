const updateTemplateSchema = templateFieldsSchema.extend({ id: z.string().min(1), status: z.enum(['draft', 'active']).optional() });

export async function updateSmsTemplateAction(rawInput: unknown): Promise<ActionResult<SmsTemplate>> {
    const input = updateTemplateSchema.parse(rawInput);
    const ctx = await requireEffectivePermission('canViewSMS');

    const { data, error } = await ctx.client.from('sms_templates').update({
        category_id: input.categoryId, name: input.name,
        text_ka: input.textKa, text_ru: input.textRu, text_en: input.textEn,
        trigger_type: input.triggerType, event_key: input.eventKey || null,
        recipient_scope: input.recipientScope, recipient_target_id: input.recipientTargetId || null,
        ...(input.status ? { status: input.status } : {}),
        updated_at: new Date().toISOString(),
    }).eq('id', input.id).eq('org_id', ctx.orgId).select('*').single();
    if (error) return fail('update_failed', error.message);

    await logAudit(ctx, 'template_edited', 'template', input.id, { name: input.name });
    revalidatePath('/sms-manager');
    return ok(mapTemplate(data as TemplateRow));
}

