export type SmsCategory = {
    id: string;
    name: string;
    color: string | null;
    icon: string | null;
    moduleKey: string | null;
    enabled: boolean;
    createdAt: string;
};

export type SmsTemplate = {
    id: string;
    categoryId: string;
    name: string;
    textKa: string;
    textRu: string;
    textEn: string;
    triggerType: 'manual' | 'event';
    eventKey: string | null;
    recipientScope: 'all' | 'group' | 'branch' | 'person';
    recipientTargetId: string | null;
    status: 'draft' | 'active';
    frequencyLimitCount: number | null;
    frequencyLimitDays: number | null;
    isAutoGenerated: boolean;
    createdAt: string;
    updatedAt: string;
};

type CategoryRow = {
    id: string; name: string; color: string | null; icon: string | null;
    module_key: string | null; enabled: boolean; created_at: string;
};

type TemplateRow = {
    id: string; category_id: string; name: string; text_ka: string; text_ru: string; text_en: string;
    trigger_type: 'manual' | 'event'; event_key: string | null;
    recipient_scope: 'all' | 'group' | 'branch' | 'person'; recipient_target_id: string | null;
    status: 'draft' | 'active'; frequency_limit_count: number | null; frequency_limit_days: number | null;
    is_auto_generated: boolean; created_at: string; updated_at: string;
};

function mapCategory(r: CategoryRow): SmsCategory {
    return { id: r.id, name: r.name, color: r.color, icon: r.icon, moduleKey: r.module_key, enabled: r.enabled, createdAt: r.created_at };
}

function mapTemplate(r: TemplateRow): SmsTemplate {
    return {
        id: r.id, categoryId: r.category_id, name: r.name, textKa: r.text_ka, textRu: r.text_ru, textEn: r.text_en,
        triggerType: r.trigger_type, eventKey: r.event_key, recipientScope: r.recipient_scope, recipientTargetId: r.recipient_target_id,
        status: r.status, frequencyLimitCount: r.frequency_limit_count, frequencyLimitDays: r.frequency_limit_days,
        isAutoGenerated: r.is_auto_generated, createdAt: r.created_at, updatedAt: r.updated_at,
    };
}

/**
 * Who performed a mutation, for sms_audit_log (PRD §9's audit journal —
 * "ვინ და როდის შეასრულა კონკრეტული მოქმედება"). Best-effort: an audit
 * row is never worth failing the actual mutation over.
 */
async function resolveActor(ctx: DualAuthContext): Promise<{ id: string | null; name: string | null }> {
    try {
        if (!ctx.isStaffToken) {
            const { data } = await ctx.client.auth.getUser();
            const meta = data?.user?.user_metadata as Record<string, unknown> | undefined;
            return { id: data?.user?.id ?? null, name: (meta?.full_name as string) || data?.user?.email || null };
        }
        if (!ctx.staffId) return { id: null, name: null };
        const { data } = await ctx.client.from('staff').select('first_name, last_name').eq('id', ctx.staffId).maybeSingle();
        const name = data ? [data.first_name, data.last_name].filter(Boolean).join(' ') : null;
        return { id: ctx.staffId, name: name || null };
    } catch {
        return { id: null, name: null };
    }
}

async function logAudit(ctx: DualAuthContext, action: string, targetType: 'category' | 'template', targetId: string, details?: Record<string, unknown>) {
    try {
        const actor = await resolveActor(ctx);
        await ctx.client.from('sms_audit_log').insert({
            org_id: ctx.orgId, actor_id: actor.id, actor_name: actor.name,
            action, target_type: targetType, target_id: targetId, details: details ?? null,
        });
    } catch {
        // Never fail the mutation over an audit-log write.
    }
}

