const duplicateTemplateSchema = z.object({ id: z.string().min(1) });

export async function duplicateSmsTemplateAction(rawInput: unknown): Promise<ActionResult<SmsTemplate>> {
    const input = duplicateTemplateSchema.parse(rawInput);
    const ctx = await requireEffectivePermission('canViewSMS');

    const { data: original, error: fetchErr } = await ctx.client.from('sms_templates').select('*').eq('id', input.id).eq('org_id', ctx.orgId).maybeSingle();
    if (fetchErr) return fail('query_failed', fetchErr.message);
    if (!original) return fail('not_found', 'Template not found');

    const row = original as TemplateRow;
    const id = crypto.randomUUID();
    const { data, error } = await ctx.client.from('sms_templates').insert({
        id, org_id: ctx.orgId, category_id: row.category_id, name: `${row.name} (copy)`,
        text_ka: row.text_ka, text_ru: row.text_ru, text_en: row.text_en,
        trigger_type: row.trigger_type, event_key: row.event_key,
        recipient_scope: row.recipient_scope, recipient_target_id: row.recipient_target_id,
        status: 'draft', frequency_limit_count: row.frequency_limit_count, frequency_limit_days: row.frequency_limit_days,
        is_auto_generated: false,
    }).select('*').single();
    if (error) return fail('insert_failed', error.message);

    await logAudit(ctx, 'template_duplicated', 'template', id, { fromId: input.id });
    revalidatePath('/sms-manager');
    return ok(mapTemplate(data as TemplateRow));
}
