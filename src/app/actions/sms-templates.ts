async function seedDefaultCategoryIfEmpty(ctx: DualAuthContext): Promise<void> {
    const { count } = await ctx.client.from('sms_categories').select('id', { count: 'exact', head: true }).eq('org_id', ctx.orgId);
    if ((count ?? 0) > 0) return;

    const categoryId = crypto.randomUUID();
    const { error: catErr } = await ctx.client.from('sms_categories').insert({
        id: categoryId, org_id: ctx.orgId, name: 'ზოგადი', color: null, icon: null, module_key: null, enabled: true,
    });
    if (catErr) return;

    await ctx.client.from('sms_templates').insert(SEED_TEMPLATES.map(t => ({
        id: crypto.randomUUID(), org_id: ctx.orgId, category_id: categoryId, name: t.name,
        text_ka: t.ka, text_ru: t.ru, text_en: t.en, trigger_type: t.triggerType, event_key: t.eventKey,
        recipient_scope: 'all', recipient_target_id: null, status: 'active', is_auto_generated: true,
    })));
}

export async function listSmsCategoriesAction(): Promise<ActionResult<SmsCategory[]>> {
    const ctx = await requireEffectivePermission('canViewSMS');
    await seedDefaultCategoryIfEmpty(ctx);

    const { data, error } = await ctx.client.from('sms_categories').select('*').eq('org_id', ctx.orgId).order('created_at', { ascending: true });
    if (error) return fail('query_failed', error.message);
    return ok((data as CategoryRow[]).map(mapCategory));
}

const createCategorySchema = z.object({ name: z.string().trim().min(1), color: z.string().trim().optional(), icon: z.string().trim().optional() });

export async function createSmsCategoryAction(rawInput: unknown): Promise<ActionResult<SmsCategory>> {
    const input = createCategorySchema.parse(rawInput);
    const ctx = await requireEffectivePermission('canViewSMS');

    const id = crypto.randomUUID();
    const { data, error } = await ctx.client.from('sms_categories')
        .insert({ id, org_id: ctx.orgId, name: input.name, color: input.color || null, icon: input.icon || null, module_key: null, enabled: true })
        .select('*').single();
    if (error) return fail('insert_failed', error.message);

    await logAudit(ctx, 'category_created', 'category', id, { name: input.name });
    revalidatePath('/sms-manager');
    return ok(mapCategory(data as CategoryRow));
}

const toggleCategorySchema = z.object({ id: z.string().min(1), enabled: z.boolean() });

